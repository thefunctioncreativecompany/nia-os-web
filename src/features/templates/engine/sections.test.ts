import { describe, expect, it } from 'vitest';
import schemas from '../../../data/template-schemas.json';
import type { TemplateSchema } from '../types';
import { canEdit, filledCount, hasContent, initDocument, resolveDocument, restoreDocument } from './sections';
import { formatClock, formatDateTimeRange, formatDays } from './format';

// The data file directly: tests don't resolve the app's `@/` paths that catalog.ts uses.
const getSchema = (code: string) => (schemas as unknown as { templates: TemplateSchema[] }).templates.find((s) => s.code === code) ?? null;
const notice = getSchema('D07')!;

describe('template engine sections', () => {
  it('opens reviewed templates, and not ones still to build', () => {
    expect(canEdit(notice)).toBe(true);
    for (const code of ['D03', 'D06', 'D08', 'D13', 'D14', 'D10']) expect(canEdit(getSchema(code))).toBe(true);
    expect(canEdit(getSchema('D01'))).toBe(false);
    expect(canEdit(null)).toBe(false);
  });

  it('starts blank, with the letter pre-filled', () => {
    const [fields, letter] = initDocument(notice);
    expect(Object.keys(fields as object)).toHaveLength(11);
    expect((fields as Record<string, unknown>)['Dates / Times']).toEqual({ from: '', to: '', start: '', end: '' });
    expect((fields as Record<string, unknown>)['Parking Restrictions']).toEqual({ answer: '', note: '' });
    expect(letter).toMatch(/^Dear Business Owners & Residents/);
    expect(filledCount(notice, initDocument(notice))).toBe(0);
  });

  it('counts a section once something real is in it', () => {
    const [fieldsSection, letterSection] = notice.sections;
    expect(hasContent(fieldsSection, { Location: '   ' })).toBe(false);
    expect(hasContent(fieldsSection, { Location: 'Griffith Park' })).toBe(true);
    expect(hasContent(letterSection, (letterSection as { default: string }).default)).toBe(false);
    expect(hasContent(letterSection, 'Dear neighbours,')).toBe(true);
  });

  it('restores saved work and fills gaps from the template', () => {
    const restored = restoreDocument(notice, [{ Location: 'Griffith Park' }]);
    expect((restored[0] as Record<string, string>).Location).toBe('Griffith Park');
    expect((restored[0] as Record<string, string>)['Phone Contact']).toBe('');
    expect(restored[1]).toMatch(/^Dear Business Owners/);
    expect(restoreDocument(notice, 'not a list')).toEqual(initDocument(notice));
  });
});

describe('template engine downloads', () => {
  it('writes Markdown and plain text with every field, blanks as a dash', async () => {
    const { toMarkdown, toPlainText, fileName } = await import('./export');
    const data = restoreDocument(notice, [{ Location: 'Griffith Park' }, 'Dear neighbours,\n\nThank you.']);
    const md = toMarkdown(notice, data);
    expect(md).toMatch(/^# Filming Notice\n\n## Notice Metadata\n\n- \*\*Production Company:\*\* —/);
    expect(md).toContain('- **Location:** Griffith Park');
    expect(md).toContain('## Notice Body\n\nDear neighbours,\n\nThank you.');
    expect(md.trimEnd().endsWith(`Generated by Nia · ${notice.version}`)).toBe(true);
    expect(toPlainText(notice, data)).toMatch(/^Filming Notice\n==============\n\nNotice Metadata\n---------------\nProduction Company: —/);
    expect(fileName(notice, 'md')).toBe('filming-notice.md');
  });
});

describe('typed answers (T5)', () => {
  it('reads dates and times naturally', () => {
    expect(formatDays('2026-08-12', '2026-08-14')).toBe('Aug 12–14, 2026');
    expect(formatDays('2026-08-30', '2026-09-02')).toBe('Aug 30 – Sep 2, 2026');
    expect(formatDays('2026-12-30', '2027-01-02')).toBe('Dec 30, 2026 – Jan 2, 2027');
    expect(formatDays('2026-08-12', '')).toBe('Aug 12, 2026');
    expect(formatClock('05:00')).toBe('5:00 AM');
    expect(formatClock('23:30')).toBe('11:30 PM');
    expect(formatDateTimeRange({ from: '2026-08-12', to: '2026-08-14', start: '05:00', end: '23:00' })).toBe('Aug 12–14, 2026 · 5:00 AM – 11:00 PM');
  });

  it('counts a picked date or a yes/no as filled', () => {
    const [fieldsSection] = notice.sections;
    expect(hasContent(fieldsSection, { 'Dates / Times': { from: '2026-08-12', to: '', start: '', end: '' } })).toBe(true);
    expect(hasContent(fieldsSection, { 'Parking Restrictions': { answer: 'no', note: '' } })).toBe(true);
    expect(hasContent(fieldsSection, { 'Parking Restrictions': { answer: '', note: '' } })).toBe(false);
  });

  it('fills the letter from the answers, wherever a placeholder is left', () => {
    const data = restoreDocument(notice, [{ 'Production Company': 'Meridian Pictures', Title: 'Meridian', 'Dates / Times': { from: '2026-08-12', to: '2026-08-14', start: '05:00', end: '23:00' } }]);
    const letter = resolveDocument(notice, data)[1] as string;
    expect(letter).toContain('Meridian Pictures will be filming scenes for the upcoming production "Meridian" in your neighbourhood on Aug 12–14, 2026.');
    expect(letter).toContain('[Location Manager]');
    expect(filledCount(notice, data)).toBe(2);
  });

  it('keeps old text answers and drops answers with the wrong shape', () => {
    const restored = restoreDocument(notice, [{ Location: 'Griffith Park', 'Dates / Times': 'Aug 12' }]);
    expect((restored[0] as Record<string, unknown>).Location).toBe('Griffith Park');
    expect((restored[0] as Record<string, unknown>)['Dates / Times']).toEqual({ from: '', to: '', start: '', end: '' });
  });
});

describe('tables (step 7 part 2)', () => {
  const rental = getSchema('D08')!;
  const table = rental.sections[1] as import('../types').TableSection;

  it('starts with blank typed rows', () => {
    const rows = initDocument(rental)[1] as Record<string, unknown>[];
    expect(rows).toHaveLength(table.rows);
    expect(rows[0]).toMatchObject({ QTY: '', 'Date Out': '', Status: '' });
    expect(typeof rows[0].id).toBe('string');
    expect(hasContent(table, rows as never)).toBe(false);
  });

  it('counts a row once a cell is filled, and keeps rows through a save', () => {
    const data = restoreDocument(rental, [{}, [{ id: 'a', QTY: '2', Equipment: 'ARRI SkyPanel', 'Date Out': '2026-08-12', Status: 'Out' }]]);
    expect(hasContent(table, data[1])).toBe(true);
    expect((data[1] as Record<string, unknown>[])[0]).toMatchObject({ id: 'a', QTY: '2', 'Date In': '', Status: 'Out' });
  });

  it('writes tables into the downloads', async () => {
    const { toMarkdown, toPlainText } = await import('./export');
    const shot = getSchema('D14')!;
    const data = restoreDocument(shot, [{}, [{ id: 'a', 'File / Take': 'A001_C003', Length: { amount: '42', unit: 'seconds' }, Use: true }]]);
    const md = toMarkdown(shot, data);
    expect(md).toContain('| File / Take | Description | Length | Comments | Use |');
    expect(md).toContain('| A001_C003 | — | 42 seconds | — | Yes |');
    expect(toPlainText(shot, data)).toContain('1. File / Take: A001_C003 · Description: — · Length: 42 seconds');
    expect(toMarkdown(getSchema('D06')!, restoreDocument(getSchema('D06')!, [{}, [{ id: 'x', 'I/E': 'EXT' }]]))).toContain('| 01 | EXT |');
  });
});
