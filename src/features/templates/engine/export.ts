import type { TableSection, TemplateSchema } from '../types';
import { formatMoney } from './format';
import { budgetTable, budgetTotals, computeCell, documentCurrency, editableColumns, fieldLabel, formatField, refResolver, resolveDocument, tableTotal, type BudgetValue, type ChecklistValue, type FieldsValue, type SectionValue, type TableRow } from './sections';

/*
 * Downloads (Ika, 2026-10-19): PDF, Word, Markdown and plain text, all built from the same
 * section data the editor shows. The PDF is a real file that downloads straight away (Ika's
 * feedback: the print screen was confusing); Print stays in the toolbar for paper.
 */

type Block = { title: string } & (
  | { kind: 'fields'; rows: [string, string][] }
  | { kind: 'table'; header: string[]; cells: string[][]; total?: [string, string] }
  | { kind: 'text'; text: string }
);

const EMPTY = '—';

// Answers as words (dates and yes/no read naturally) and letters with their placeholders filled.
function blocks(schema: TemplateSchema, data: SectionValue[]): Block[] {
  const shown = resolveDocument(schema, data);
  const currency = documentCurrency(schema, data);
  // A table as rows of words, with its worked-out columns and total.
  const tableBlock = (section: TableSection, rows: TableRow[]): Block => {
    const columns = editableColumns(section);
    const numbered = section.autonumber ? [section.autonumber] : [];
    const computed = Object.keys(section.computed ?? {});
    const money = (column: string, amount: number) => {
      if (section.money?.includes(column)) return formatMoney(amount, currency);
      const spec = section.columns.find((c) => fieldLabel(c) === column);
      return spec ? formatField(spec, String(amount)) || '0' : String(amount);
    };
    const total = tableTotal(section, rows);
    return {
      title: section.title,
      kind: 'table',
      header: [...numbered, ...columns.map(fieldLabel), ...computed],
      cells: rows.map((row, r) => [
        ...(section.autonumber ? [String(r + 1).padStart(2, '0')] : []),
        ...columns.map((c) => formatField(c, row[fieldLabel(c)], { currency, ref: refResolver(schema, data, typeof c === 'string' ? undefined : c.source) }) || EMPTY),
        ...computed.map((column) => {
          const amount = computeCell(section, row, column);
          return amount === null ? EMPTY : money(column, amount);
        }),
      ]),
      total: section.total && total !== null ? [section.total.label, money(section.total.column, total)] : undefined,
    };
  };
  return schema.sections.flatMap((section, i): Block[] => {
    const value = shown[i];
    if (section.type === 'fields') {
      const fields = (value ?? {}) as FieldsValue;
      return [{ title: section.title, kind: 'fields', rows: section.fields.map((f) => [fieldLabel(f), formatField(f, fields[fieldLabel(f)], { currency }) || EMPTY]) }];
    }
    // A checklist downloads as a table of its items with whether each is done.
    if (section.type === 'checklist') {
      const groups = (value as ChecklistValue)?.checklist ?? [];
      return [{
        title: section.title,
        kind: 'table',
        header: ['When', 'Item', 'Done'],
        cells: section.groups.flatMap((g, gi) => (groups[gi] ?? []).filter((i) => i.text.trim()).map((i) => [g.label, i.text.trim(), i.done ? 'Yes' : EMPTY])),
      }];
    }
    if (section.type === 'categories') {
      const answers = (value ?? {}) as FieldsValue;
      return [{ title: section.title, kind: 'fields', rows: section.items.map((item) => [item, String(answers[item] ?? '').trim() || EMPTY]) }];
    }
    // A budget downloads as one table per group, then the summary.
    if (section.type === 'budget') {
      const budget = value as BudgetValue;
      const totals = budgetTotals(section, budget);
      const money = (amount: number) => formatMoney(amount, currency);
      return [
        ...section.groups.map((_, gi) => tableBlock(budgetTable(section, gi), budget?.groups?.[gi] ?? [])),
        {
          title: 'Budget summary',
          kind: 'fields',
          rows: [
            ...section.groups.map((g, gi): [string, string] => [g.label, money(totals.groups[gi])]),
            [`Contingency (${Math.round(totals.percent)}%)`, money(totals.contingency)],
            ['Total budget', money(totals.total)],
          ],
        },
      ];
    }
    if (section.type === 'table') return [tableBlock(section, (Array.isArray(value) ? value : []) as TableRow[])];
    return [{ title: section.title, kind: 'text', text: typeof value === 'string' && value.trim() ? value.trim() : EMPTY }];
  });
}

const footer = (schema: TemplateSchema) => `Generated by Nia · ${schema.version}`;

export function toMarkdown(schema: TemplateSchema, data: SectionValue[], branded = true) {
  const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const body = blocks(schema, data).map((b) => {
    if (b.kind === 'fields') return `## ${b.title}\n\n${b.rows.map(([label, value]) => `- **${label}:** ${value}`).join('\n')}`;
    if (b.kind === 'table') {
      const line = (cells: string[]) => `| ${cells.map(cell).join(' | ')} |`;
      const total = b.total ? [line([...b.header.slice(2).map(() => ''), `**${b.total[0]}**`, `**${b.total[1]}**`].slice(-b.header.length))] : [];
      return `## ${b.title}\n\n${[line(b.header), line(b.header.map(() => '---')), ...b.cells.map(line), ...total].join('\n')}`;
    }
    return `## ${b.title}\n\n${b.text}`;
  });
  return `# ${schema.name}\n\n${body.join('\n\n')}\n${branded ? `\n---\n\n${footer(schema)}\n` : ''}`;
}

export function toPlainText(schema: TemplateSchema, data: SectionValue[], branded = true) {
  const underline = (text: string, char: string) => `${text}\n${char.repeat(text.length)}`;
  const body = blocks(schema, data).map((b) => {
    if (b.kind === 'fields') return `${underline(b.title, '-')}\n${b.rows.map(([label, value]) => `${label}: ${value}`).join('\n')}`;
    if (b.kind === 'table') {
      const rows = b.cells.map((cells, r) => `${r + 1}. ${cells.map((c, i) => `${b.header[i]}: ${c}`).join(' · ')}`);
      return `${underline(b.title, '-')}\n${rows.join('\n') || EMPTY}${b.total ? `\n${b.total[0]}: ${b.total[1]}` : ''}`;
    }
    return `${underline(b.title, '-')}\n${b.text}`;
  });
  return `${underline(schema.name, '=')}\n\n${body.join('\n\n')}\n${branded ? `\n${footer(schema)}\n` : ''}`;
}

/** A real .docx. The library loads only when someone downloads one. */
export async function toWord(schema: TemplateSchema, data: SectionValue[], branded = true): Promise<Blob> {
  const { Document, HeadingLevel, Packer, Paragraph, Table, TableCell, TableRow: Row, TextRun, WidthType } = await import('docx');
  const children: (InstanceType<typeof Paragraph> | InstanceType<typeof Table>)[] = [new Paragraph({ text: schema.name, heading: HeadingLevel.HEADING_1 })];
  for (const b of blocks(schema, data)) {
    children.push(new Paragraph({ text: b.title, heading: HeadingLevel.HEADING_2, spacing: { before: 240 } }));
    if (b.kind === 'fields') {
      for (const [label, value] of b.rows)
        children.push(new Paragraph({ children: [new TextRun({ text: `${label}: `, bold: true }), new TextRun(value)] }));
    } else if (b.kind === 'table') {
      const row = (cells: string[], bold = false) =>
        new Row({ children: cells.map((c) => new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: c, bold })] })] })) });
      children.push(new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, rows: [row(b.header, true), ...b.cells.map((c) => row(c))] }));
      if (b.total) children.push(new Paragraph({ children: [new TextRun({ text: `${b.total[0]}: ${b.total[1]}`, bold: true })], spacing: { before: 120 } }));
    } else {
      for (const line of b.text.split('\n')) children.push(new Paragraph({ text: line }));
    }
  }
  if (branded) children.push(new Paragraph({ children: [new TextRun({ text: footer(schema), size: 16, color: '73726C' })], spacing: { before: 480 } }));
  return Packer.toBlob(new Document({ creator: 'Nia', title: schema.name, sections: [{ children }] }));
}

// The brand in PDF terms (jsPDF takes colours as numbers, so these mirror the theme tokens):
// foreground, muted-foreground, border and nia-panel from globals.css.
const INK: [number, number, number] = [10, 9, 8];
const MUTED: [number, number, number] = [115, 114, 108];
const RULE: [number, number, number] = [226, 226, 226];
const PANEL: [number, number, number] = [249, 249, 250];

// Fetched once per visit: the live preview builds the PDF every time the document changes.
const fonts = new Map<string, Promise<string>>();
function fontData(file: string) {
  if (!fonts.has(file)) {
    const loading = (async () => {
      const bytes = new Uint8Array(await (await fetch(`/fonts/${file}`)).arrayBuffer());
      let binary = '';
      for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
      return btoa(binary);
    })();
    loading.catch(() => fonts.delete(file));
    fonts.set(file, loading);
  }
  return fonts.get(file)!;
}

/** A real PDF in Geist, US Letter. The library and fonts load only when someone downloads one. */
export async function toPdf(schema: TemplateSchema, data: SectionValue[], branded = true): Promise<Blob> {
  const [{ jsPDF }, { autoTable }, regular, bold] = await Promise.all([
    import('jspdf'),
    import('jspdf-autotable'),
    fontData('Geist-Regular.ttf'),
    fontData('Geist-Bold.ttf'),
  ]);
  const pdf = new jsPDF({ unit: 'pt', format: 'letter' });
  pdf.addFileToVFS('Geist-Regular.ttf', regular);
  pdf.addFont('Geist-Regular.ttf', 'Geist', 'normal');
  pdf.addFileToVFS('Geist-Bold.ttf', bold);
  pdf.addFont('Geist-Bold.ttf', 'Geist', 'bold');
  pdf.setProperties({ title: schema.name, creator: 'Nia' });

  const margin = 48;
  const width = pdf.internal.pageSize.getWidth() - margin * 2;
  const bottom = pdf.internal.pageSize.getHeight() - margin - 16;
  let y = margin;
  const room = (needed: number) => {
    if (y + needed <= bottom) return;
    pdf.addPage();
    y = margin;
  };
  const after = () => (pdf as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
  const base = { font: 'Geist', textColor: INK, lineColor: RULE, cellPadding: { top: 5, bottom: 5, left: 6, right: 6 } } as const;

  pdf.setFont('Geist', 'bold').setFontSize(22).setTextColor(...INK);
  pdf.text(schema.name, margin, y + 18);
  y += 36;

  for (const b of blocks(schema, data)) {
    room(48);
    y += 14;
    pdf.setFont('Geist', 'bold').setFontSize(12).setTextColor(...INK);
    pdf.text(b.title, margin, y);
    y += 6;
    pdf.setDrawColor(...INK).setLineWidth(1).line(margin, y, margin + width, y);
    y += 4;
    if (b.kind === 'fields') {
      autoTable(pdf, {
        startY: y,
        margin: { left: margin, right: margin },
        theme: 'plain',
        body: b.rows,
        styles: { ...base, fontSize: 9.5, lineWidth: { bottom: 0.5 } },
        columnStyles: { 0: { cellWidth: width * 0.32, textColor: MUTED } },
      });
      y = after() + 6;
    } else if (b.kind === 'table') {
      autoTable(pdf, {
        startY: y + 4,
        margin: { left: margin, right: margin },
        theme: 'grid',
        head: [b.header],
        body: b.cells.length ? b.cells : [b.header.map((_, i) => (i === 0 ? EMPTY : ''))],
        foot: b.total ? [[...b.header.slice(0, -2).map(() => ''), b.total[0], b.total[1]].slice(-b.header.length)] : undefined,
        showFoot: 'lastPage',
        styles: { ...base, fontSize: 8.5, lineWidth: 0.5 },
        headStyles: { fontStyle: 'bold', fillColor: PANEL, textColor: MUTED },
        footStyles: { fontStyle: 'bold', fillColor: PANEL, textColor: INK },
      });
      y = after() + 6;
    } else {
      pdf.setFont('Geist', 'normal').setFontSize(10).setTextColor(...INK);
      y += 10;
      for (const line of pdf.splitTextToSize(b.text, width) as string[]) {
        room(14);
        pdf.text(line, margin, y);
        y += 14;
      }
    }
  }

  // Every page carries its page number, and the Nia footer unless a paid plan turned it off.
  const pages = pdf.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    pdf.setPage(page);
    pdf.setFont('Geist', 'normal').setFontSize(8).setTextColor(...MUTED);
    const footY = pdf.internal.pageSize.getHeight() - margin / 2;
    if (branded) pdf.text(footer(schema), margin, footY);
    pdf.text(`Page ${page} of ${pages}`, margin + width, footY, { align: 'right' });
  }
  return pdf.output('blob');
}

export const fileName = (schema: TemplateSchema, extension: string) =>
  `${schema.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.${extension}`;

export function downloadFile(name: string, content: Blob | string, type = 'text/plain;charset=utf-8') {
  const blob = typeof content === 'string' ? new Blob([content], { type }) : content;
  const url = URL.createObjectURL(blob);
  const link = Object.assign(document.createElement('a'), { href: url, download: name });
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
