import type { TemplateSchema } from '../types';
import type { FieldsValue, SectionValue } from './sections';

/*
 * Downloads besides PDF (Ika, 2026-10-19): Markdown, Word and plain text, built from the same
 * section data the editor shows. PDF is the browser's print, so it isn't here.
 */

type Block = { title: string } & ({ kind: 'fields'; rows: [string, string][] } | { kind: 'text'; text: string });

const EMPTY = '—';

function blocks(schema: TemplateSchema, data: SectionValue[]): Block[] {
  return schema.sections.map((section, i) => {
    const value = data[i];
    if (section.type === 'fields') {
      const fields = (value ?? {}) as FieldsValue;
      return { title: section.title, kind: 'fields', rows: section.fields.map((f) => [f, fields[f]?.trim() || EMPTY]) };
    }
    return { title: section.title, kind: 'text', text: typeof value === 'string' && value.trim() ? value.trim() : EMPTY };
  });
}

const footer = (schema: TemplateSchema) => `Generated by Nia · ${schema.version}`;

export function toMarkdown(schema: TemplateSchema, data: SectionValue[]) {
  const body = blocks(schema, data).map((b) =>
    b.kind === 'fields'
      ? `## ${b.title}\n\n${b.rows.map(([label, value]) => `- **${label}:** ${value}`).join('\n')}`
      : `## ${b.title}\n\n${b.text}`,
  );
  return `# ${schema.name}\n\n${body.join('\n\n')}\n\n---\n\n${footer(schema)}\n`;
}

export function toPlainText(schema: TemplateSchema, data: SectionValue[]) {
  const underline = (text: string, char: string) => `${text}\n${char.repeat(text.length)}`;
  const body = blocks(schema, data).map((b) =>
    b.kind === 'fields'
      ? `${underline(b.title, '-')}\n${b.rows.map(([label, value]) => `${label}: ${value}`).join('\n')}`
      : `${underline(b.title, '-')}\n${b.text}`,
  );
  return `${underline(schema.name, '=')}\n\n${body.join('\n\n')}\n\n${footer(schema)}\n`;
}

/** A real .docx. The library loads only when someone downloads one. */
export async function toWord(schema: TemplateSchema, data: SectionValue[]): Promise<Blob> {
  const { Document, HeadingLevel, Packer, Paragraph, TextRun } = await import('docx');
  const children = [new Paragraph({ text: schema.name, heading: HeadingLevel.HEADING_1 })];
  for (const b of blocks(schema, data)) {
    children.push(new Paragraph({ text: b.title, heading: HeadingLevel.HEADING_2, spacing: { before: 240 } }));
    if (b.kind === 'fields') {
      for (const [label, value] of b.rows)
        children.push(new Paragraph({ children: [new TextRun({ text: `${label}: `, bold: true }), new TextRun(value)] }));
    } else {
      for (const line of b.text.split('\n')) children.push(new Paragraph({ text: line }));
    }
  }
  children.push(new Paragraph({ children: [new TextRun({ text: footer(schema), size: 16, color: '73726C' })], spacing: { before: 480 } }));
  return Packer.toBlob(new Document({ creator: 'Nia', title: schema.name, sections: [{ children }] }));
}

export const fileName = (schema: TemplateSchema, extension: string) =>
  `${schema.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}.${extension}`;

export function downloadFile(name: string, content: Blob | string, type = 'text/plain;charset=utf-8') {
  const blob = typeof content === 'string' ? new Blob([content], { type }) : content;
  const url = URL.createObjectURL(blob);
  const link = Object.assign(document.createElement('a'), { href: url, download: name });
  document.body.append(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
